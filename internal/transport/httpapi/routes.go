	api.POST("/auth/access/preview", s.wrap(s.authPreview))
	api.GET("/auth/users", s.wrap(s.authUsers))
	api.POST("/auth/users", s.wrap(s.authCreate))
	api.PUT("/auth/users/:user_id", s.wrap(s.authUpdate))
	api.GET("/presentation/scenario", s.wrap(s.presentationScenario))
	api.GET("/presentation/summary", s.wrap(s.presentationSummary))
	api.GET("/wells", s.wrap(s.listWells))
	api.POST("/wells", s.wrap(s.createWell))
	api.POST("/wells/bulk", s.wrap(s.bulkWells))
	api.POST("/wells/import", s.wrap(s.importWells))
