	api.GET("/wells/:well_id/telemetry/bounds", s.wrap(s.appTelemetryBounds))
	api.POST("/wells/:well_id/telemetry/score", s.wrap(s.appTelemetryScore))
	api.GET("/wells/:well_id/checks", s.wrap(s.manualChecks))
	api.POST("/wells/:well_id/checks", s.wrap(s.createManualCheck))
	api.GET("/wells/:well_id/checks/:check_id", s.wrap(s.manualCheck))
	api.GET("/wells/:well_id/checks/:check_id/review", s.wrap(s.checkReview))
	api.PUT("/wells/:well_id/checks/:check_id/review", s.wrap(s.updateCheckReview))
	api.GET("/ml/alerts/:alert_id/review", s.wrap(s.alertReview))
	api.PUT("/ml/alerts/:alert_id/review", s.wrap(s.updateAlertReview))
	api.GET("/wells/:well_id/risk", s.wrap(s.mlByAppWell))
