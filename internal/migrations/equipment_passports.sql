 target_well_ids bigint[] NOT NULL CHECK(cardinality(target_well_ids) BETWEEN 1 AND 100),
 preview_id bigint NOT NULL REFERENCES equipment_passport_preview(id) ON DELETE RESTRICT,
 digest text NOT NULL CHECK(digest ~ '^[0-9a-f]{64}$'),
 app_scope text NOT NULL CHECK(app_scope IN ('research','cohort')), cohort_version text NOT NULL,
 source text NOT NULL CHECK(source IN ('manual','excel')),
 recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
