-- Additive18: каталог прав/существующие well и RBAC assignments не изменяются.
-- Unrestricted numeric + checks: numeric(15,6) не представляет разрешённый 1e9.
CREATE DOMAIN equipment_passport_decimal AS numeric CHECK (
 VALUE >= 0 AND VALUE <= 1000000000 AND scale(trim_scale(VALUE)) <= 6
 AND length(ltrim(split_part(trim_scale(VALUE)::text,'.',1),'0')) + length(split_part(trim_scale(VALUE)::text,'.',2)) <= 15
);
CREATE TABLE equipment_passport (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 well_id bigint NOT NULL UNIQUE REFERENCES well(id) ON DELETE RESTRICT,
 revision bigint NOT NULL DEFAULT 0 CHECK(revision>=0)
);
CREATE TABLE equipment_passport_component (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 passport_id bigint NOT NULL REFERENCES equipment_passport(id) ON DELETE RESTRICT,
 slot text NOT NULL CHECK(slot IN ('pump','motor','control_station')),
 model text CHECK(model=btrim(model) AND char_length(model) BETWEEN 1 AND 200),
 manufacturer text CHECK(manufacturer=btrim(manufacturer) AND char_length(manufacturer) BETWEEN 1 AND 200),
 serial_number text CHECK(serial_number=btrim(serial_number) AND char_length(serial_number) BETWEEN 1 AND 120),
 pump_nominal_flow_m3_day equipment_passport_decimal CHECK(pump_nominal_flow_m3_day>0),
 pump_nominal_head_m equipment_passport_decimal CHECK(pump_nominal_head_m>0),
 pump_stage_count bigint CHECK(pump_stage_count BETWEEN 1 AND 100000),
 motor_rated_power_kw equipment_passport_decimal CHECK(motor_rated_power_kw>0),
 motor_rated_voltage_v equipment_passport_decimal CHECK(motor_rated_voltage_v>0),
 motor_rated_current_a equipment_passport_decimal CHECK(motor_rated_current_a>0),
 motor_nominal_frequency_hz equipment_passport_decimal CHECK(motor_nominal_frequency_hz>0),
 control_rated_power_kw equipment_passport_decimal CHECK(control_rated_power_kw>0),
 control_rated_voltage_v equipment_passport_decimal CHECK(control_rated_voltage_v>0),
 control_rated_current_a equipment_passport_decimal CHECK(control_rated_current_a>0),
 control_output_frequency_min_hz equipment_passport_decimal,
 control_output_frequency_max_hz equipment_passport_decimal CHECK(control_output_frequency_max_hz>0),
 UNIQUE(id,passport_id,slot),
 CHECK(control_output_frequency_min_hz IS NULL OR control_output_frequency_max_hz IS NULL OR control_output_frequency_min_hz<=control_output_frequency_max_hz),
 CHECK(slot='pump' OR (pump_nominal_flow_m3_day IS NULL AND pump_nominal_head_m IS NULL AND pump_stage_count IS NULL)),
 CHECK(slot='motor' OR (motor_rated_power_kw IS NULL AND motor_rated_voltage_v IS NULL AND motor_rated_current_a IS NULL AND motor_nominal_frequency_hz IS NULL)),
 CHECK(slot='control_station' OR (control_rated_power_kw IS NULL AND control_rated_voltage_v IS NULL AND control_rated_current_a IS NULL AND control_output_frequency_min_hz IS NULL AND control_output_frequency_max_hz IS NULL))
 );
CREATE TABLE equipment_passport_installation (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 passport_id bigint NOT NULL REFERENCES equipment_passport(id) ON DELETE RESTRICT,
 component_id bigint NOT NULL UNIQUE,
 slot text NOT NULL CHECK(slot IN ('pump','motor','control_station')),
 status text NOT NULL CHECK(status IN ('current','closed','voided')),
 installed_on date, removed_on date, predecessor_id bigint UNIQUE,
 UNIQUE(id,passport_id,slot),
 FOREIGN KEY(component_id,passport_id,slot) REFERENCES equipment_passport_component(id,passport_id,slot) ON DELETE RESTRICT,
 FOREIGN KEY(predecessor_id,passport_id,slot) REFERENCES equipment_passport_installation(id,passport_id,slot) ON DELETE RESTRICT,
 CHECK(predecessor_id IS NULL OR predecessor_id<>id),
 CHECK(installed_on IS NULL OR removed_on IS NULL OR removed_on>installed_on),
 CHECK(status<>'current' OR removed_on IS NULL)
);
CREATE UNIQUE INDEX equipment_passport_current_slot ON equipment_passport_installation(passport_id,slot) WHERE status='current';
